data <- purrr::imap_dfr(
  synthetic_data_prepared,
  
  function(dataset_list, method_name) {
    
    purrr::map2_dfr(
      dataset_list,
      seq_along(dataset_list),
      
      function(df, replicate_id) {
        
        df |>
          dplyr::mutate(
            group = method_name,
            replicate = replicate_id
          )
      }
    )
  }
)


